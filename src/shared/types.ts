export type AgentStatus = 'starting' | 'idle' | 'working' | 'needs_input' | 'done' | 'offline';

export type HookEventType =
  | 'SessionStart'
  | 'UserPromptSubmit'
  | 'PreToolUse'
  | 'Notification'
  | 'Stop'
  | 'SessionEnd';

/** Body POSTed to /events by hooks/send-event.mjs. */
export interface IncomingEvent {
  repo: string;
  sessionId?: string;
  tmuxSession?: string;
  type: HookEventType | string;
  tool?: string;
  command?: string;
  message?: string;
  cwd?: string;
  timestamp?: string;
}

export interface AgentEvent {
  id: number;
  agentId: string;
  repo: string;
  type: string;
  tool?: string;
  command?: string;
  message?: string;
  timestamp: string;
}

export interface Agent {
  /** tmux session name when known, otherwise the Claude session id. */
  id: string;
  repo: string;
  /** Display name for agents the server runs ("<repo>-<n>"); for tmux agents also the tmux session name. */
  tmuxSession?: string;
  sessionId?: string;
  /** How the server controls this agent, if it does. */
  runner?: 'tmux' | 'pty';
  status: AgentStatus;
  /** Session title generated by Claude Code (from the transcript). */
  title?: string;
  /** Directory the session started in. */
  cwd?: string;
  /** % of the context window in use (from the status line). */
  contextPercent?: number;
  model?: string;
  currentTask?: string;
  lastPrompt?: string;
  startedAt: string;
  lastEventAt?: string;
  /**
   * Earlier session ids of this same agent. The claude process in an agent's terminal can switch to a new session id
   * (`/clear`, or "start new instead of resuming"); the agent follows it and keeps the old ids here.
   */
  previousSessionIds?: string[];
  /** PID of the claude process while this session is open anywhere (from ~/.claude/sessions). */
  livePid?: number;
  /** Claude Code's own live status for the open session. */
  liveStatus?: 'busy' | 'idle' | 'waiting';
  /** What the session is waiting for when liveStatus is "waiting" (e.g. a permission dialog). */
  waitingFor?: string;
  /** True if the server can type into this agent (live tmux session or server-owned terminal). */
  controllable: boolean;
}

export interface RepoInfo {
  name: string;
  path?: string;
}

export interface LimitWindow {
  usedPercentage: number;
  /** Unix epoch seconds. */
  resetsAt: number;
}

/** Account-wide Claude subscription limits, as last reported by any session's status line. */
export interface UsageLimits {
  fiveHour?: LimitWindow;
  sevenDay?: LimitWindow;
  /** ISO time of the last report. */
  updatedAt?: string;
}

/** Body POSTed to /usage by hooks/statusline.mjs. */
export interface IncomingUsage {
  sessionId?: string;
  cwd?: string;
  model?: string;
  contextPercent?: number;
  fiveHour?: LimitWindow;
  sevenDay?: LimitWindow;
}

export type ServerMessage =
  | { type: 'usage'; usage: UsageLimits }
  | {
      type: 'snapshot';
      agents: Agent[];
      repos: RepoInfo[];
      events: Record<string, AgentEvent[]>;
      /** Whether "+ New agent" / "Take over" can work on this machine. */
      canLaunch: boolean;
      /** Cap on agents the app runs at once per repo. */
      maxAgentsPerRepo: number;
      usage: UsageLimits;
    }
  | { type: 'agent'; agent: Agent }
  | { type: 'agentRemoved'; id: string }
  /** Replaces an agent's whole event log (e.g. after two agents were merged into one). */
  | { type: 'agentEvents'; agentId: string; events: AgentEvent[] }
  | { type: 'event'; event: AgentEvent }
  | { type: 'repos'; repos: RepoInfo[] };
